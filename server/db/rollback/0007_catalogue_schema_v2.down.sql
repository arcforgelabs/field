DO $$
DECLARE
  c record;
BEGIN
  FOR c IN
    SELECT conname FROM pg_constraint
    WHERE conrelid = '"kit_components"'::regclass AND conname LIKE 'kit\_components\_%' AND contype <> 'p'
  LOOP
    EXECUTE format('ALTER TABLE "kit_components" RENAME CONSTRAINT %I TO %I', c.conname,
      CASE c.conname
        WHEN 'kit_components_kit_fk' THEN 'item_components_parent_fk'
        WHEN 'kit_components_component_fk' THEN 'item_components_child_fk'
        ELSE replace(replace(replace(c.conname, 'kit_components_', 'item_components_'), 'kit_uid', 'parent_uid'), 'component_uid', 'child_uid')
      END);
  END LOOP;
END
$$;
